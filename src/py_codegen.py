"""Phase 6: Python backend. Resolved AST -> executable Python 3 source.

MiniB is statically typed, so the generated module is valid Python as-is:
`int`, `float`, `str`, `bool`, `None`, `and/or/not`, `print`, `len` and
`input` all have the same meaning in both languages.

Block scoping is preserved by renaming shadowed variables (`x$1` -> `x__1`)
during semantic analysis, because Python only has function-level scopes.
"""
import dataclasses

from . import ast_nodes as A


def _name(node) -> str:
    """Resolved name of a declaration/assignment."""
    return (
        getattr(node, "resolved_name", None)
        or getattr(node, "resolved", None)
        or node.name
    )


def _collect_original_names(items: list) -> set[str]:
    """Names written in the source; reserved so renamed shadows cannot clash."""
    found: set[str] = set()

    def walk(obj):
        if dataclasses.is_dataclass(obj):
            for f in dataclasses.fields(obj):
                val = getattr(obj, f.name)
                if f.name in ("name", "resolved", "resolved_name") and isinstance(val, str):
                    if (f.name == "name" or "$" not in val) and val.isidentifier():
                        found.add(val)
                else:
                    walk(val)
        elif isinstance(obj, (list, tuple)):
            for x in obj:
                walk(x)

    walk(items)
    return found


def _collect_globals(items: list) -> set[str]:
    """Resolved names of top-level `let` statements."""
    names: set[str] = set()

    def walk(stmts):
        for s in stmts:
            if isinstance(s, A.LetStmt):
                names.add(_name(s))
            elif isinstance(s, A.Block):
                walk(s.stmts)
            elif isinstance(s, A.ForStmt) and isinstance(s.init, A.LetStmt):
                names.add(_name(s.init))

    walk(items)
    return names


def _assigned_names(stmts: list) -> set[str]:
    """Resolved names assigned by a function body (used for Python `global`)."""
    names: set[str] = set()

    def walk(ss):
        for s in ss:
            if isinstance(s, A.AssignStmt):
                names.add(_name(s))
            elif isinstance(s, A.SetIndexStmt):
                names.add(_name(s.target))
            elif isinstance(s, A.Block):
                walk(s.stmts)
            elif isinstance(s, A.IfStmt):
                walk(s.then_body)
                walk(s.else_body)
            elif isinstance(s, A.WhileStmt):
                walk(s.body)
            elif isinstance(s, A.ForStmt):
                walk([s.init, s.update])
                walk(s.body)

    walk(stmts)
    return names


class _Names:
    def __init__(self, reserved: set[str]):
        self.used = set(reserved)
        self.map: dict[str, str] = {}

    def __call__(self, name: str) -> str:
        if "$" not in name:
            return name
        if name in self.map:
            return self.map[name]
        base = name.replace("$", "__")
        candidate = base
        n = 2
        while candidate in self.used:
            candidate = f"{base}_{n}"
            n += 1
        self.used.add(candidate)
        self.map[name] = candidate
        return candidate


class PythonCodeGen:
    def __init__(self):
        self.lines: list[str] = []
        self.level = 0
        self.names = _Names(set())
        self.global_names: set[str] = set()
        self.continue_hooks: list = []

    # -- output helpers --
    def emit(self, line: str = ""):
        self.lines.append(("    " * self.level + line) if line else "")

    def body(self, stmts: list):
        self.level += 1
        if not stmts:
            self.emit("pass")
        for s in stmts:
            self.stmt(s)
        self.level -= 1

    # -- entry --
    def generate(self, prog: A.Program) -> str:
        self.names = _Names(_collect_original_names(prog.items))
        self.global_names = _collect_globals(prog.items)
        self.emit("# Generated by MiniB (python backend)")
        self.emit()
        for it in prog.items:
            if isinstance(it, A.FuncDef):
                self.func(it)
            else:
                self.stmt(it)
        while self.lines and self.lines[-1] == "":
            self.lines.pop()
        return "\n".join(self.lines) + "\n"

    def func(self, fn: A.FuncDef):
        params = ", ".join(self.names(p.name) for p in fn.params)
        ret = "" if fn.ret == "None" else f" -> {fn.ret}"
        self.emit(f"def {fn.name}({params}){ret}:")
        globals_written = sorted(
            _assigned_names(fn.body) & self.global_names
        )
        self.level += 1
        if globals_written:
            self.emit("global " + ", ".join(self.names(n) for n in globals_written))
        if not fn.body and not globals_written:
            self.emit("pass")
        for s in fn.body:
            self.stmt(s)
        self.level -= 1
        self.emit()

    # -- statements --
    def stmt(self, s):
        if isinstance(s, A.Block):
            if not s.stmts:
                self.emit("pass")
            for x in s.stmts:
                self.stmt(x)
        elif isinstance(s, A.LetStmt):
            self.emit(f"{self.names(_name(s))} = {self.expr(s.expr)}")
        elif isinstance(s, A.AssignStmt):
            self.emit(f"{self.names(_name(s))} = {self.expr(s.expr)}")
        elif isinstance(s, A.IfStmt):
            self.if_stmt(s)
        elif isinstance(s, A.WhileStmt):
            self.emit(f"while {self.expr(s.cond)}:")
            self.continue_hooks.append(None)
            self.body(s.body)
            self.continue_hooks.pop()
        elif isinstance(s, A.ForStmt):
            self.for_stmt(s)
        elif isinstance(s, A.BreakStmt):
            self.emit("break")
        elif isinstance(s, A.ContinueStmt):
            hook = self.continue_hooks[-1] if self.continue_hooks else None
            if hook is not None:
                hook()  # `for` update must run before `continue`
            self.emit("continue")
        elif isinstance(s, A.SetIndexStmt):
            target = self.names(_name(s.target))
            self.emit(
                f"{target}[{self.expr(s.index)}] = {self.expr(s.expr)}"
            )
        elif isinstance(s, A.ReturnStmt):
            self.emit("return" if s.expr is None else f"return {self.expr(s.expr)}")
        elif isinstance(s, A.ExprStmt):
            self.emit(self.expr(s.expr))
        else:
            raise ValueError(f"unknown statement {type(s).__name__}")

    def if_stmt(self, s: A.IfStmt, keyword: str = "if"):
        self.emit(f"{keyword} {self.expr(s.cond)}:")
        self.body(s.then_body)
        if not s.else_body:
            return
        if len(s.else_body) == 1 and isinstance(s.else_body[0], A.IfStmt):
            self.if_stmt(s.else_body[0], "elif")
        else:
            self.emit("else:")
            self.body(s.else_body)

    def for_stmt(self, s: A.ForStmt):
        self.stmt(s.init)
        self.emit(f"while {self.expr(s.cond)}:")
        self.level += 1
        self.continue_hooks.append(lambda: self.stmt(s.update))
        if not s.body:
            self.emit("pass")
        for x in s.body:
            self.stmt(x)
        self.continue_hooks.pop()
        self.stmt(s.update)
        self.level -= 1

    # -- expressions --
    def expr(self, e) -> str:
        if isinstance(e, A.Literal):
            if e.lit_type == "str":
                return repr(e.value)
            if e.lit_type == "bool":
                return "True" if e.value else "False"
            if e.value is None:
                return "None"
            return repr(e.value)
        if isinstance(e, A.Var):
            return self.names(getattr(e, "resolved", e.name))
        if isinstance(e, A.ListLit):
            items = ", ".join(self.expr(x) for x in e.items)
            return f"[{items}]"
        if isinstance(e, A.Index):
            return f"{self.expr(e.target)}[{self.expr(e.index)}]"
        if isinstance(e, A.UnaryOp):
            op = "not " if e.op == "not" else "-"
            return f"({op}{self.expr(e.operand)})"
        if isinstance(e, A.BinOp):
            return f"({self.expr(e.left)} {e.op} {self.expr(e.right)})"
        if isinstance(e, A.Call):
            args = ", ".join(self.expr(a) for a in e.args)
            return f"{e.name}({args})"
        raise ValueError(f"unknown expression {type(e).__name__}")


def generate_python(prog: A.Program) -> str:
    return PythonCodeGen().generate(prog)
